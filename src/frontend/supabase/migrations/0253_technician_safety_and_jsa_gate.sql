-- 0253 — Technicians hold `safety`, and jsa_assessments answers to the matrix
--
-- The matrix said TECHNICIAN safety: NO_ACCESS while JSATab, WorkOrders and
-- RecurringWork all read jsa_assessments from surfaces technicians live on. A
-- technician completes the JSA on their own job and performs the lockout —
-- withholding `safety` was an error in the matrix, not a leak in the code, and
-- gating the table against the old value would have broken the job.
--
-- So TECHNICIAN gains safety: VIEW_ONLY (read, no create/edit/delete) and the
-- table is gated on it. Side effect worth naming: /comply/psm and /comply/loto
-- are also keyed on `safety`, so technicians can now read those too. LOTO is
-- plainly theirs. PSM is process-safety documentation — read-only access is
-- appropriate for the people working inside those boundaries.
--
-- The seed below is REGENERATED, not hand-edited (npm run gen:role-permissions).
-- It re-seeds role_permissions wholesale, which is why it can live in a new
-- migration rather than editing 0241 — applied migrations are immutable and the
-- runner's checksum guard enforces that.
-- ════════════════════════════════════════════════════════════════════════════

DO $$
DECLARE r record;
BEGIN
    -- Drop everything granting SELECT, FOR ALL included: RLS is OR-ed, so one
    -- surviving USING (true) leaves the gate decorative.
    FOR r IN SELECT policyname, cmd FROM pg_policies
             WHERE schemaname='public' AND tablename='jsa_assessments' AND cmd IN ('SELECT','ALL')
    LOOP
        EXECUTE format('DROP POLICY IF EXISTS %I ON public.jsa_assessments', r.policyname);
        IF r.cmd = 'ALL' THEN
            EXECUTE 'DROP POLICY IF EXISTS auth_insert_jsa_assessments ON public.jsa_assessments';
            EXECUTE 'DROP POLICY IF EXISTS auth_update_jsa_assessments ON public.jsa_assessments';
            EXECUTE 'DROP POLICY IF EXISTS auth_delete_jsa_assessments ON public.jsa_assessments';
            EXECUTE 'CREATE POLICY auth_insert_jsa_assessments ON public.jsa_assessments FOR INSERT TO authenticated WITH CHECK (true)';
            EXECUTE 'CREATE POLICY auth_update_jsa_assessments ON public.jsa_assessments FOR UPDATE TO authenticated USING (true) WITH CHECK (true)';
            EXECUTE 'CREATE POLICY auth_delete_jsa_assessments ON public.jsa_assessments FOR DELETE TO authenticated USING (true)';
        END IF;
    END LOOP;
END $$;

ALTER TABLE public.jsa_assessments ENABLE ROW LEVEL SECURITY;
CREATE POLICY rbac_select_jsa_assessments ON public.jsa_assessments
    FOR SELECT TO authenticated
    USING ((SELECT public.caller_can('safety', 'view')));

