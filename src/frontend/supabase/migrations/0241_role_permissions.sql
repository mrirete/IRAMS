-- ════════════════════════════════════════════════════════════════════════════
-- 0241 — RBAC Phase 1: make the permission matrix readable from SQL
--
-- Nothing uses this yet. That is deliberate: the mechanism lands and is proved
-- against the TypeScript matrix BEFORE any policy depends on it, so a failure
-- here is a failing test rather than an app that will not load.
--
-- Why a mirror table rather than role names in policies: policies keyed on
-- users.roles duplicate the matrix in SQL and drift the moment someone edits a
-- template. They also cannot see per-user permission_overrides, so an admin
-- withdrawing one module from one person would work in the UI and not in the
-- API — the exact split the route-gate fix just closed. 0197 hit this and left
-- a comment recommending "a permission-backed check". This is that.
--
-- Source of truth stays in TypeScript. The seed block below is GENERATED by
-- scripts/gen-role-permissions.mjs, and rolePermissionsMirror.test.ts fails if
-- the two disagree, so the mirror cannot silently rot.
-- ════════════════════════════════════════════════════════════════════════════

CREATE TABLE IF NOT EXISTS public.role_permissions (
    role   TEXT NOT NULL,
    module TEXT NOT NULL,
    action TEXT NOT NULL,
    PRIMARY KEY (role, module, action)
);

COMMENT ON TABLE public.role_permissions IS
    'Mirror of ROLE_PERMISSION_TEMPLATES for RLS. A row means PERMITTED; absence means not. Generated — edit rolePermissions.ts and run `npm run gen:role-permissions`. Role __default__ carries BASE_PACKAGE_DEFAULTS, used for roles with no template (fail-closed).';

ALTER TABLE public.role_permissions ENABLE ROW LEVEL SECURITY;

-- Readable only by admins. caller_can() does NOT depend on this policy — it is
-- SECURITY DEFINER and bypasses RLS — so tightening here cannot lock the app
-- out of its own permission checks.
--
-- ⚠ NEVER put a caller_can() policy on this table. caller_can() reads it, so
-- that is infinite recursion, and it would take down every query in the app.
DROP POLICY IF EXISTS admin_select_role_permissions ON public.role_permissions;
CREATE POLICY admin_select_role_permissions ON public.role_permissions
    FOR SELECT TO authenticated USING (public.is_admin());

-- ── The decision, with no notion of identity ────────────────────────────────
-- Split out so it can be tested exhaustively over every role × module × action
-- without needing a login for each role. IMMUTABLE: same inputs, same answer.
--
-- Reproduces AuthContext's merge exactly (AuthContext.tsx ~L219-229):
--   • the role is users.roles[0] only — not "any of the user's roles"
--   • an override sets one ACTION; it does not replace the module
--   • an override of FALSE withdraws permission. It must not fall through to
--     the template, which is why this tests IS NOT NULL rather than truthiness.
CREATE OR REPLACE FUNCTION public.role_can(
    p_role      text,
    p_overrides jsonb,
    p_module    text,
    p_action    text
) RETURNS boolean
LANGUAGE sql IMMUTABLE
SET search_path = public
AS $$
    SELECT CASE
        WHEN p_overrides -> p_module ->> p_action IS NOT NULL
            THEN (p_overrides -> p_module ->> p_action)::boolean
        ELSE EXISTS (
            SELECT 1 FROM public.role_permissions rp
            WHERE rp.role   = coalesce(p_role, '__default__')
              AND rp.module = p_module
              AND rp.action = p_action
        )
    END;
$$;

COMMENT ON FUNCTION public.role_can(text, jsonb, text, text) IS
    'Pure permission decision: role template + per-user overrides. An override of false WITHDRAWS. Tested exhaustively against the TypeScript matrix by tests/rls/caller-can-parity.mjs.';

-- ── The same decision, for whoever is calling ───────────────────────────────
-- ⚠ SECURITY DEFINER is load-bearing, not decoration. This function reads
-- `users`; if it ran as the caller and `users` ever gained a policy that called
-- caller_can(), Postgres would recurse until every query failed — login
-- included. Do not remove it, and do not gate `users` with caller_can().
--
-- STABLE with constant arguments lets Postgres hoist this to an InitPlan, so an
-- RLS policy evaluates it once per statement rather than once per row. is_admin()
-- relies on the same property.
--
-- Identity resolution is copied from is_admin() (0171) on purpose. If the two
-- ever disagree about who you are, admin rights and module rights diverge, and
-- that is a miserable bug to chase.
--
-- users.roles is JSONB (contacts.roles is text[] — different table, same name),
-- hence `roles ->> 0` rather than an array subscript.
CREATE OR REPLACE FUNCTION public.caller_can(p_module text, p_action text)
RETURNS boolean
LANGUAGE sql STABLE SECURITY DEFINER
SET search_path = public
AS $$
    WITH me AS (
        SELECT u.roles ->> 0 AS role,
               coalesce(u.permission_overrides, '{}'::jsonb) AS overrides
        FROM public.users u
        WHERE (
                lower(coalesce(u.email, '')) = lower(coalesce(auth.jwt() ->> 'email', ''))
             OR lower(coalesce(u.username, '')) = lower(split_part(coalesce(auth.jwt() ->> 'email', ''), '@', 1))
              )
          AND coalesce(u.status, 'active') = 'active'
        LIMIT 1
    )
    -- No matching row → role is NULL → role_can falls back to __default__
    -- (BASE_PACKAGE_DEFAULTS, fail-closed). Same posture AuthContext takes.
    SELECT public.role_can(
        (SELECT role FROM me),
        coalesce((SELECT overrides FROM me), '{}'::jsonb),
        p_module,
        p_action
    );
$$;

COMMENT ON FUNCTION public.caller_can(text, text) IS
    'Does the CALLER hold module.action? SECURITY DEFINER — it reads users, so never gate users/role_permissions with it (infinite recursion). Use in RLS as: USING (public.caller_can(''finops'',''view'')).';

REVOKE ALL ON FUNCTION public.role_can(text, jsonb, text, text) FROM public;
REVOKE ALL ON FUNCTION public.caller_can(text, text)            FROM public;
GRANT EXECUTE ON FUNCTION public.role_can(text, jsonb, text, text) TO authenticated;
GRANT EXECUTE ON FUNCTION public.caller_can(text, text)            TO authenticated;

